"""Build the article's numeric tables from the measured JSON files."""

import json
from pathlib import Path

PAPER = Path(__file__).resolve().parent
RESULTS = PAPER.parent / "results" / "processed"


def load(name):
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


def decimal(value, digits):
    return f"{value:.{digits}f}".replace(".", "{,}")


def row(*cells):
    return " & ".join(map(str, cells)) + r" \\"


def render_tables():
    validation = load("validation.json")
    plants = load("plant-summary.json")
    delay = load("pade-summary.json")
    bench = load("benchmark-summary.json")
    methods = ("Nyquist", "Routh--Hurwitz", "Lugar das raízes", "Bode")
    data = dict(zip(methods, ("Nyquist", "Routh-Hurwitz", "Lugar das Raízes", "Bode"), strict=True))

    nominal_rows = []
    for entry in plants:
        gain = entry["phase_crossings_rad_s_gm"]
        phase = entry["gain_crossings_rad_s_pm_deg"]
        nominal_rows.append(row(
            entry["system"], f'$({entry["p"]},{entry["n"]},{entry["z"]})$',
            "$" + decimal(gain[0][1], 3) + "$" if gain else "--",
            "$" + decimal(phase[0][1], 2) + "$" if phase else "--",
        ))
    delay_rows = [
        row(
            order["order"],
            "$" + decimal(order["critical_delay_s"], 7) + "$",
            "$" + decimal(order["critical_relative_error"] * 100, 5) + r"\%$",
            "estável" if order["status_at_1p01_exact"] == "stable" else "instável",
        )
        for order in delay["orders"]
    ]
    cpu_rows = [
        row(method, *(
            "$" + decimal(item["median_cpu_ms"], 3) + "$"
            for item in bench["timings"] if item["method"] == data[method]
        ))
        for method in methods
    ]
    macros = {
        "ChecksPass": validation["passed"],
        "ChecksTotal": validation["total"],
        "DelayCritical": "$" + decimal(delay["critical_exact_computed_s"], 5) + "$",
        "NominalRows": "\n".join(nominal_rows),
        "DelayRows": "\n".join(delay_rows),
        "CpuRows": "\n".join(cpu_rows),
    }
    content = "% Generated by paper/build_tables.py from results/processed/.\n"
    for key, value in macros.items():
        content += f"\\newcommand{{\\{key}}}{{{value}}}\n"
    (PAPER / "tables.generated.tex").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    render_tables()
